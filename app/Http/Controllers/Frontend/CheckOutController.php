<?php

namespace App\Http\Controllers\Frontend;

use App\Http\Controllers\Controller;
use App\Interfaces\ShippingruleRepositoryInterface;
use App\Interfaces\UserAddressRepositoryInterface;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\Session;

class CheckOutController extends Controller
{
    public function index()
    {
        $addresses = app(UserAddressRepositoryInterface::class)->getAllByUserId(Auth::user()->id);
        $shippingMethods = app(ShippingruleRepositoryInterface::class)->getActiveShippingRules();
        return view('frontend.pages.checkout', compact('addresses', 'shippingMethods'));
    }

    public function createAddress(Request $request)
    {
        $request->validate([
            'name' => ['required', 'max:200'],
            'phone' => ['required', 'max:200'],
            'email' => ['required', 'email'],
            'country' => ['required', 'max: 200'],
            'state' => ['required', 'max: 200'],
            'city' => ['required', 'max: 200'],
            'zip' => ['required', 'max: 200'],
            'address' => ['required', 'max: 200']
        ]);

        $data = [
            'user_id' => Auth::user()->id,
            'name' => $request->name,
            'phone' => $request->phone,
            'email' => $request->email,
            'country' => $request->country,
            'state' => $request->state,
            'city' => $request->city,
            'zip' => $request->zip,
            'address' => $request->address,
        ];

        app(UserAddressRepositoryInterface::class)->create($data);

        toastr('Address created successfully!', 'success', 'Success');

        return redirect()->back();
    }

    public function checkOutFormSubmit(Request $request)
    {
       $request->validate([
        'shipping_method_id' => ['required', 'integer'],
        'shipping_address_id' => ['required', 'integer'],
       ]);

       $shippingMethod = app(ShippingruleRepositoryInterface::class)->getById($request->shipping_method_id);
       if($shippingMethod){
           Session::put('shipping_method', [
                'id' => $shippingMethod->id,
                'name' => $shippingMethod->name,
                'type' => $shippingMethod->type,
                'cost' => $shippingMethod->cost
           ]);
       }
       $address = app(UserAddressRepositoryInterface::class)->getById($request->shipping_address_id)->toArray();
       if($address){
           Session::put('address', $address);
       }

       return response(['status' => 'success', 'redirect_url' => route('user.payment')]);
    }
}
